// Generate Quadlet (SPEC §10.20 "Podman only"): a `.container` unit for systemd made from the settings of a container, opened as an
// untitled editor. Emetos never writes it to ~/.config/containers/systemd or /etc/containers/systemd and never runs systemctl: the user
// saves it where they want it (podman-systemd.unit(5)). The unit has only what the user gave the container: the environment,
// command, labels and user that the image has itself are left out, and so are the variables Podman sets by itself.

// quadletHost is the part of Podman's inspect that the typed ContainerInspect does not hold.
type quadletHost struct {
	HostConfig struct {
		RestartPolicy struct {
			Name string `json:"Name"`
		} `json:"RestartPolicy"`
		NetworkMode string `json:"NetworkMode"`
	} `json:"HostConfig"`
}

// podmanSetEnv are the variables Podman puts in the environment of a container itself, with the value that shows it was Podman.
var podmanSetEnv = map[string]func(value string, info *containerapi.ContainerInspect) bool{
	"container": func(v string, _ *containerapi.ContainerInspect) bool { return v == "podman" },
	"HOME": func(v string, _ *containerapi.ContainerInspect) bool {
		return v == "/root" || strings.HasPrefix(v, "/home/")
	},
	"HOSTNAME": func(v string, info *containerapi.ContainerInspect) bool {
		return v == info.Hostname || v == containerapi.ShortID(info.ID)
	},
	"TERM": func(v string, _ *containerapi.ContainerInspect) bool { return v == "xterm" },
}

// generateQuadlet writes the unit of a container. image is the inspect of its image, nil when it could not be read (then nothing is
// left out as "the image's own"). It fails with ContainerUIQuadletInvalid when the inspect cannot be read.
func generateQuadlet(info *containerapi.ContainerInspect, image *containerapi.ImageInspect) (string, error) {
	var host quadletHost
	if len(info.Raw) > 0 {
		if err := json.Unmarshal(info.Raw, &host); err != nil {
			return "", errors.NewErr("ContainerUIQuadletInvalid", err).SetMetadata("container", info.Name)
		}
	}
	if info.ImageName == "" && info.Image == "" {
		return "", errors.New("ContainerUIQuadletInvalid", "the inspect of the container names no image", "container", info.Name)
	}
	name := strings.TrimPrefix(info.Name, "/")
	var b strings.Builder
	b.WriteString("# Generated by Emetos from the container " + quadletComment(name) + ".\n")
	b.WriteString("# Save it as " + quadletFileName(name) + ".container in ~/.config/containers/systemd/ (rootless) or /etc/containers/systemd/ (rootful),\n")
	b.WriteString("# then run `systemctl --user daemon-reload` (or `systemctl daemon-reload` as root) and start " + quadletFileName(name) + ".service.\n")
	b.WriteString("# Emetos does not install it. See podman-systemd.unit(5) for the keys.\n")
	if info.Pod != "" {
		b.WriteString("# The container is in a pod. A pod is a .pod unit of its own, not generated here: add Pod=<name>.pod if you make one.\n")
	}
	b.WriteString("\n[Unit]\nDescription=" + quadletText(name) + "\n\n[Container]\n")
	line := func(key, value string) { b.WriteString(key + "=" + value + "\n") }
	if name != "" {
		line("ContainerName", quadletText(name))
	}
	img := info.ImageName
	if img == "" {
		img = info.Image
	}
	line("Image", quadletText(img))

	var imgEnv, imgCmd, imgEntry []string
	var imgLabels map[string]string
	var imgUser, imgWorkDir string
	if image != nil {
		imgEnv, imgCmd, imgEntry, imgLabels, imgUser, imgWorkDir = image.Env, image.Cmd, image.Entrypoint, image.Labels, image.User, image.WorkingDir
	}
	if len(info.Entrypoint) > 0 && !slices.Equal(info.Entrypoint, imgEntry) {
		line("Entrypoint", quadletWords(info.Entrypoint))
	}
	if len(info.Cmd) > 0 && !slices.Equal(info.Cmd, imgCmd) {
		line("Exec", quadletWords(info.Cmd))
	}
	for _, kv := range info.Env {
		if slices.Contains(imgEnv, kv) {
			continue
		}
		k, v, _ := strings.Cut(kv, "=")
		if own, ok := podmanSetEnv[k]; ok && own(v, info) {
			continue
		}
		line("Environment", quadletAssignment(kv))
	}
	for _, p := range quadletPorts(info.Ports) {
		line("PublishPort", p)
	}
	for _, m := range info.Mounts {
		src := m.Source
		if m.Type == "volume" && m.Name != "" {
			src = m.Name
		}
		if src == "" || m.Destination == "" || m.Type == "tmpfs" {
			continue
		}
		v := src + ":" + m.Destination
		if !m.RW {
			v += ":ro"
		}
		line("Volume", quadletText(v))
	}
	for _, n := range quadletNetworks(info.Networks, host.HostConfig.NetworkMode) {
		line("Network", quadletText(n))
	}
	if info.WorkingDir != "" && info.WorkingDir != "/" && info.WorkingDir != imgWorkDir {
		line("WorkingDir", quadletText(info.WorkingDir))
	}
	if info.User != "" && info.User != imgUser {
		line("User", quadletText(info.User))
	}
	if info.Hostname != "" && info.Hostname != containerapi.ShortID(info.ID) && info.Hostname != name {
		line("HostName", quadletText(info.Hostname))
	}
	keys := make([]string, 0, len(info.Labels))
	for k := range info.Labels {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		if strings.HasPrefix(k, "io.podman.") || strings.HasPrefix(k, "com.docker.compose.") {
			continue
		}
		if iv, ok := imgLabels[k]; ok && iv == info.Labels[k] {
			continue
		}
		line("Label", quadletAssignment(k+"="+info.Labels[k]))
	}
	if r := quadletRestart(host.HostConfig.RestartPolicy.Name); r != "" {
		b.WriteString("\n[Service]\nRestart=" + r + "\n")
	}
	b.WriteString("\n[Install]\nWantedBy=default.target\n")
	return b.String(), nil
}

// quadletRestart maps the restart policy of a container to the Restart= of the service ("" for none): always and unless-stopped
// are always (systemd has no "unless stopped": a service the user stopped stays stopped), on-failure is on-failure.
func quadletRestart(policy string) string {
	switch policy {
	case "always", "unless-stopped":
		return "always"
	case "on-failure":
		return "on-failure"
	}
	return ""
}

// quadletNetworks lists the Network= lines: the networks other than Podman's default ones, and the mode when it is not the usual
// bridge.
func quadletNetworks(networks []string, mode string) []string {
	var out []string
	switch mode {
	case "", "default", "bridge", "podman":
	case "host", "none", "slirp4netns", "pasta":
		return []string{mode}
	default:
		if strings.HasPrefix(mode, "container:") || strings.HasPrefix(mode, "ns:") {
			return nil
		}
	}
	for _, n := range networks {
		if n == "podman" || n == "bridge" || n == "" {
			continue
		}
		out = append(out, n)
	}
	return out
}

// quadletPorts lists the PublishPort= values: [host address:]host port:container port[/protocol].
func quadletPorts(ports map[string][]containerapi.PortBinding) []string {
	keys := make([]string, 0, len(ports))
	for k := range ports {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var out []string
	for _, k := range keys {
		port, proto, _ := strings.Cut(k, "/")
		suffix := ""
		if proto != "" && proto != "tcp" {
			suffix = "/" + proto
		}
		for _, b := range ports[k] {
			var v string
			switch {
			case b.HostIP != "" && b.HostIP != "0.0.0.0":
				ip := b.HostIP
				if strings.Contains(ip, ":") {
					ip = "[" + ip + "]" // an IPv6 address is written in brackets
				}
				v = ip + ":" + b.HostPort + ":" + port
			case b.HostPort != "":
				v = b.HostPort + ":" + port
			default:
				continue // exposed, not published
			}
			out = append(out, v+suffix)
		}
	}
	return out
}

// quadletFileName is the name of the unit file for a container: its name, with what a file name cannot hold replaced.
func quadletFileName(name string) string {
	var b strings.Builder
	for _, r := range name {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '-', r == '_', r == '.':
			b.WriteRune(r)
		default:
			b.WriteRune('-')
		}
	}
	if b.Len() == 0 {
		return "container"
	}
	return b.String()
}

// quadletComment makes a name safe for a comment line (no line break).
func quadletComment(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "\n", " "), "\r", " ")
}

// specifiers doubles the % of a value: a unit file reads %n as a specifier.
func specifiers(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "\r", ""), "%", "%%")
}

// quadletText escapes a value for a key that holds one plain word (an image, a path): the specifier % is doubled and a line break
// becomes a space (a unit file has one value to a line).
func quadletText(s string) string { return strings.ReplaceAll(specifiers(s), "\n", " ") }

// quadletAssignment writes a KEY=value of Environment= or Label= the way systemd reads them: the whole assignment in double quotes
// when it has anything but plain characters.
func quadletAssignment(kv string) string {
	kv = specifiers(kv)
	if !needsQuotes(kv) {
		return kv
	}
	return `"` + escapeQuoted(kv) + `"`
}

// quadletWords writes a command line (Exec=, Entrypoint=) as systemd reads it: words separated by spaces, a word with anything
// but plain characters in double quotes, and $ doubled (a command line of a unit substitutes variables).
func quadletWords(words []string) string {
	out := make([]string, len(words))
	for i, w := range words {
		w = strings.ReplaceAll(specifiers(w), "$", "$$")
		switch {
		case w == "":
			out[i] = `""`
		case w == ";":
			out[i] = `\;`
		case needsQuotes(w):
			out[i] = `"` + escapeQuoted(w) + `"`
		default:
			out[i] = w
		}
	}
	return strings.Join(out, " ")
}

// needsQuotes tells whether a word has a space, a quote, a backslash or a line break.
func needsQuotes(s string) bool {
	return s == "" || strings.ContainsAny(s, " \t\n\"'\\")
}

// escapeQuoted escapes what a double-quoted word of a unit file must not hold as it is: the backslash, the quote and the line break.
func escapeQuoted(s string) string {
	return strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`).Replace(s)
}

// generateQuadletFor reads the container and its image and opens the unit in an untitled editor.
func (e *ext) generateQuadletFor(c containerapi.Container) {
	client, ok := e.ready()
	if !ok {
		return
	}
	go func() {
		ctx := e.ctx
		info, err := client.InspectContainer(ctx, c.ID)
		var image *containerapi.ImageInspect
		if err == nil {
			ref := info.Image
			if ref == "" {
				ref = info.ImageName
			}
			// the image only tells what to leave out, so a failure here is not one
			if im, ierr := client.InspectImage(ctx, ref); ierr == nil {
				image = im
			} else {
				e.api.Log().Debug("the image of the container cannot be read", "image", ref, "err", ierr)
			}
		}
		var unit string
		if err == nil {
			unit, err = generateQuadlet(info, image)
		}
		e.api.Post(func() {
			if err != nil {
				e.api.Notifications().Error("Cannot generate a Quadlet unit for " + c.Name() + ": " + reasonOf(err))
				return
			}
			e.openGenerated("ini", c.Name()+".container", unit)
		})
	}()
}

// openGenerated opens a generated text in an untitled editor of a language, so that the user can edit and save it; when the window
// cannot do that, in a read-only tab.
func (e *ext) openGenerated(language, title, text string) {
	if _, err := e.api.Documents().OpenUntitled(language, text); err != nil {
		e.api.Log().Warn("an untitled document cannot be opened", "err", err)
		e.docs.open(title, text, language)
	}
}
