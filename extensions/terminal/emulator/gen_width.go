//go:build ignore

// gen_width.go writes width_gen.go: the table of how many cells each code point takes (0, 1 or 2). It is made from the
// East Asian Width property that golang.org/x/text/width carries (Unicode's EastAsianWidth.txt) and from the general
// categories of the standard library (Mn, Me and Cf take no cell), so it needs no network and adds no license. Run it with
// "go generate ./extensions/terminal/emulator".
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"unicode"

	"golang.org/x/text/width"
)

func cellWidth(r rune) uint8 {
	switch {
	case r < 0x20 || (r >= 0x7f && r < 0xa0):
		return 0
	case r == 0xad:
		return 1
	case r >= 0x1160 && r <= 0x11ff: // Hangul Jamo medial vowels and final consonants join the previous syllable
		return 0
	case unicode.In(r, unicode.Mn, unicode.Me, unicode.Cf):
		return 0
	}
	switch width.LookupRune(r).Kind() {
	case width.EastAsianWide, width.EastAsianFullwidth:
		return 2
	}
	return 1
}

func main() {
	const pages = 0x1100
	var pageIdx [pages]uint8
	var uniq [][256]uint8
	seen := map[[256]uint8]uint8{}
	for p := 0; p < pages; p++ {
		var pg [256]uint8
		for i := range pg {
			pg[i] = cellWidth(rune(p<<8 | i))
		}
		id, ok := seen[pg]
		if !ok {
			if len(uniq) == 255 {
				log.Fatal("too many distinct pages")
			}
			id = uint8(len(uniq))
			uniq = append(uniq, pg)
			seen[pg] = id
		}
		pageIdx[p] = id
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_width.go; DO NOT EDIT.\n\npackage emulator\n\n")
	b.WriteString("// widthIndex maps a code point's high bits (r >> 8) to a page of widthPages.\n")
	b.WriteString("var widthIndex = [0x1100]uint8{")
	for i, v := range pageIdx {
		if i%32 == 0 {
			b.WriteString("\n\t")
		}
		fmt.Fprintf(&b, "%d, ", v)
	}
	b.WriteString("\n}\n\n// widthPages holds the width (0, 1 or 2 cells) of the 256 code points of each distinct page.\n")
	fmt.Fprintf(&b, "var widthPages = [%d][256]uint8{", len(uniq))
	for _, pg := range uniq {
		b.WriteString("\n\t{")
		for i, v := range pg {
			if i%64 == 0 {
				b.WriteString("\n\t\t")
			}
			fmt.Fprintf(&b, "%d, ", v)
		}
		b.WriteString("\n\t},")
	}
	b.WriteString("\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("width_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
