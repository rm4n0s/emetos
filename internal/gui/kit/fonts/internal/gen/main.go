// Command gen turns codicon.csv into codicon_gen.go: one constant for the code
// point of each codicon, and the table of the code points by short name (SPEC §10.2). Run it with go generate in
// internal/gui/kit/fonts, after scripts/update-assets.sh has copied the CSV.
package main

import (
	"bytes"
	"encoding/csv"
	"go/format"
	"io"
	"log/slog"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/rm4n0s/errors"
)

const (
	inputFile  = "codicon.csv"
	outputFile = "codicon_gen.go"
	// constPrefix starts the name of every constant: "code" is CodiconCode.
	constPrefix = "Codicon"
)

// nameRe is the shape of a codicon's short name: lowercase words joined by hyphens.
var nameRe = regexp.MustCompile(`^[a-z][a-z0-9]*(-[a-z0-9]+)*$`)

func main() {
	if err := run(inputFile, outputFile); err != nil {
		report(err)
		os.Exit(1)
	}
}

// report logs the error as JSON on stderr, so that it can be replayed in a test.
func report(err error) {
	slog.New(slog.NewJSONHandler(os.Stderr, nil)).Error("generate failed", "err", err)
}

// run reads the CSV in and writes the generated Go file out. The error tags are
// CodiconReadFailed and CodiconWriteFailed, and those of generate.
func run(in, out string) error {
	f, err := os.Open(in)
	if err != nil {
		return errors.NewErr("CodiconReadFailed", err).SetMetadata("path", in)
	}
	src, err := generate(f)
	if cerr := f.Close(); err == nil && cerr != nil {
		err = errors.NewErr("CodiconReadFailed", cerr).SetMetadata("path", in)
	}
	if err != nil {
		return err
	}
	if err := os.WriteFile(out, src, 0o644); err != nil {
		return errors.NewErr("CodiconWriteFailed", err).SetMetadata("path", out)
	}
	return nil
}

// generate returns the Go source for the codicons in the CSV (a header line
// short_name,character,unicode, then one codicon per line). The error tags are
// CodiconCSVInvalid, CodiconNameInvalid, CodiconCodeInvalid,
// CodiconNameCollision and CodiconFormatFailed.
func generate(r io.Reader) ([]byte, error) {
	rd := csv.NewReader(r)
	rd.FieldsPerRecord = 3
	header, err := rd.Read()
	if err != nil {
		return nil, errors.NewErr("CodiconCSVInvalid", err)
	}
	if got := strings.TrimPrefix(strings.Join(header, ","), "\ufeff"); got != "short_name,character,unicode" {
		return nil, errors.New("CodiconCSVInvalid", "the header is not short_name,character,unicode", "header", got)
	}
	type icon struct {
		name  string
		short string
		code  uint64
	}
	var icons []icon
	taken := map[string]string{} // Go name -> short name
	for {
		rec, err := rd.Read()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, errors.NewErr("CodiconCSVInvalid", err)
		}
		name, hex := rec[0], rec[2]
		if !nameRe.MatchString(name) {
			return nil, errors.New("CodiconNameInvalid", "the short name is not lowercase words joined by hyphens", "name", name)
		}
		code, err := strconv.ParseUint(hex, 16, 32)
		if err != nil || code == 0 {
			return nil, errors.New("CodiconCodeInvalid", "the unicode column is not a hexadecimal code point", "name", name, "unicode", hex)
		}
		goName := constPrefix + pascal(name)
		if other, dup := taken[goName]; dup {
			return nil, errors.New("CodiconNameCollision", "two short names make the same constant", "constant", goName, "names", other+" "+name)
		}
		taken[goName] = name
		icons = append(icons, icon{goName, name, code})
	}
	sort.Slice(icons, func(i, j int) bool { return icons[i].name < icons[j].name })

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen from codicon.csv; DO NOT EDIT.\n\n")
	b.WriteString("package fonts\n\n")
	b.WriteString("// The code points of the codicons in the Codicon font, named after the short\n")
	b.WriteString("// names of codicon.csv in PascalCase: \"zoom-out\" is CodiconZoomOut.\n")
	b.WriteString("const (\n")
	for _, ic := range icons {
		b.WriteString("\t" + ic.name + " = 0x" + strings.ToUpper(strconv.FormatUint(ic.code, 16)) + "\n")
	}
	b.WriteString(")\n\n")
	b.WriteString("// codiconCodes are the code points of the codicons by short name, for CodiconByName.\n")
	b.WriteString("var codiconCodes = map[string]int{\n")
	byShort := append([]icon(nil), icons...)
	sort.Slice(byShort, func(i, j int) bool { return byShort[i].short < byShort[j].short })
	for _, ic := range byShort {
		b.WriteString("\t\"" + ic.short + "\": 0x" + strings.ToUpper(strconv.FormatUint(ic.code, 16)) + ",\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, errors.NewErr("CodiconFormatFailed", err)
	}
	return src, nil
}

// pascal turns "zoom-out" into "ZoomOut".
func pascal(name string) string {
	var b strings.Builder
	for _, part := range strings.Split(name, "-") {
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}
