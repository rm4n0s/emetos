func TestPascal(t *testing.T) {
	tests := map[string]string{
		"code":                 "Code",
		"zoom-out":             "ZoomOut",
		"git-pull-request-2":   "GitPullRequest2",
		"arrow-small-up":       "ArrowSmallUp",
		"a1-b2":                "A1B2",
		"debug-breakpoint-log": "DebugBreakpointLog",
	}
	for in, want := range tests {
		if got := pascal(in); got != want {
			t.Errorf("pascal(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestGenerate(t *testing.T) {
	src, err := generate(strings.NewReader("short_name,character,unicode\nzoom-out,,EB82\nadd,,ea60\ncode,,EAC4\n"))
	if err != nil {
		t.Fatal(err)
	}
	got := string(src)
	for _, want := range []string{
		"// Code generated by internal/gen from codicon.csv; DO NOT EDIT.",
		"package fonts",
		"CodiconAdd     = 0xEA60", // sorted by name, hex in capitals, aligned by gofmt
		"CodiconCode    = 0xEAC4",
		"CodiconZoomOut = 0xEB82",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("output lacks %q:\n%s", want, got)
		}
	}
	if strings.Index(got, "CodiconAdd") > strings.Index(got, "CodiconCode") {
		t.Error("constants are not sorted by name")
	}
}

func TestGenerateErrors(t *testing.T) {
	tests := []struct {
		name string
		csv  string
		tag  string
	}{
		{"empty file", "", "CodiconCSVInvalid"},
		{"wrong header", "name,char,code\nadd,,EA60\n", "CodiconCSVInvalid"},
		{"wrong column count", "short_name,character,unicode\nadd,EA60\n", "CodiconCSVInvalid"},
		{"uppercase name", "short_name,character,unicode\nAdd,,EA60\n", "CodiconNameInvalid"},
		{"name that starts with a digit", "short_name,character,unicode\n1x,,EA60\n", "CodiconNameInvalid"},
		{"double hyphen", "short_name,character,unicode\na--b,,EA60\n", "CodiconNameInvalid"},
		{"code is not hex", "short_name,character,unicode\nadd,,XYZ\n", "CodiconCodeInvalid"},
		{"code is empty", "short_name,character,unicode\nadd,,\n", "CodiconCodeInvalid"},
		{"code is zero", "short_name,character,unicode\nadd,,0\n", "CodiconCodeInvalid"},
		{"two names make one constant", "short_name,character,unicode\na-b,,EA60\na-B,,EA61\n", "CodiconNameInvalid"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := generate(strings.NewReader(tt.csv))
			assertTag(t, err, tt.tag, "generate")
		})
	}
}

// pascal never makes one constant from two valid names, because hyphens only
// separate words; the collision tag guards against a future change to it.
func TestGenerateNameCollision(t *testing.T) {
	// "a1-b" and "a-1b" are both valid names but make A1B and A1b: no collision.
	if _, err := generate(strings.NewReader("short_name,character,unicode\na1-b,,EA60\na-1b,,EA61\n")); err != nil {
		t.Fatalf("distinct constants must not collide: %v", err)
	}
	// The same name twice does collide.
	_, err := generate(strings.NewReader("short_name,character,unicode\nadd,,EA60\nadd,,EA61\n"))
	assertTag(t, err, "CodiconNameCollision", "generate")
}

func TestRunErrors(t *testing.T) {
	dir := t.TempDir()
	assertTag(t, run(dir+"/missing.csv", dir+"/out.go"), "CodiconReadFailed", "run")

	good := dir + "/good.csv"
	if err := os.WriteFile(good, []byte("short_name,character,unicode\nadd,,EA60\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	assertTag(t, run(good, dir+"/no-such-folder/out.go"), "CodiconWriteFailed", "run")

	bad := dir + "/bad.csv"
	if err := os.WriteFile(bad, []byte("nonsense"), 0o600); err != nil {
		t.Fatal(err)
	}
	assertTag(t, run(bad, dir+"/out.go"), "CodiconCSVInvalid", "run")
}

// TestGeneratedFileIsUpToDate is the check that the generated constants match
// codicon.csv: generating again gives the committed codicon_gen.go, and every
// row of the CSV has its constant.
func TestGeneratedFileIsUpToDate(t *testing.T) {
	csvBytes, err := os.ReadFile("../../codicon.csv")
	if err != nil {
		t.Fatal(err)
	}
	committed, err := os.ReadFile("../../codicon_gen.go")
	if err != nil {
		t.Fatal(err)
	}
	fresh, err := generate(bytes.NewReader(csvBytes))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(fresh, committed) {
		t.Error("codicon_gen.go is out of date: run go generate ./internal/gui/kit/fonts")
	}

	rows, err := csv.NewReader(bytes.NewReader(csvBytes)).ReadAll()
	if err != nil {
		t.Fatal(err)
	}
	for _, row := range rows[1:] {
		want := "Codicon" + pascal(row[0]) + " = 0x" + strings.ToUpper(strings.TrimLeft(row[2], "0"))
		if !strings.Contains(strings.Join(strings.Fields(string(committed)), " "), want) {
			t.Errorf("no constant %q for the codicon %q", want, row[0])
		}
	}
	if len(rows) < 600 {
		t.Errorf("the CSV has only %d rows", len(rows))
	}
}

func assertTag(t *testing.T, err error, tag, route string) {
	t.Helper()
	appErr, ok := errors.FromError(err)
	if !ok {
		t.Fatalf("expected *errors.Error with tag %s, got %T (%v)", tag, err, err)
	}
	if appErr.Tag != tag || !appErr.HasRoute(route) {
		t.Errorf("Tag = %q, route = %s; want tag %q through %q", appErr.Tag, appErr.Route(), tag, route)
	}
}
